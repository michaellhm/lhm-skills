#!/usr/bin/env python3
"""Disposable Linux bind-mount rehearsal; never opens a production workspace."""
import argparse
import json
import os
from pathlib import Path
import shutil
import subprocess
import sys
import tempfile


CHILD = r'''
import json, os, pathlib, sys
root = pathlib.Path(sys.argv[1])
handle = open('sentinel', 'r+')
before = os.fstat(handle.fileno())
print('ready', flush=True)
assert sys.stdin.readline().strip() == 'verify'
handle.seek(0); handle.write('held-handle'); handle.flush(); os.fsync(handle.fileno())
assert pathlib.Path('sentinel').read_text() == 'held-handle'
assert (root / 'active/sentinel').read_text() == 'held-handle'
(root / 'active/sentinel').write_text('alias-write')
handle.seek(0); assert handle.read() == 'alias-write'
after = os.stat(root / 'active/sentinel')
assert (before.st_dev, before.st_ino) == (after.st_dev, after.st_ino)
print(json.dumps({'held_fd': True, 'relative_path': True, 'absolute_alias': True,
                  'same_inode': True, 'same_process': os.getpid()}), flush=True)
'''


def run(volume):
    if sys.platform != 'linux' or os.geteuid() != 0:
        raise RuntimeError('Rehearsal requires a Linux administrator')
    volume = Path(volume)
    if not volume.is_absolute() or volume.is_symlink() or not volume.is_mount():
        raise ValueError('Supply an existing absolute mounted volume')
    if volume.stat().st_dev == Path('/var/lib').stat().st_dev:
        raise ValueError('The volume must be a different filesystem')
    source = Path(tempfile.mkdtemp(prefix='lhm-dev-rehearsal-', dir='/var/lib'))
    destination = Path(tempfile.mkdtemp(prefix='lhm-dev-rehearsal-', dir=volume))
    live = source / 'live'
    legacy = source / 'legacy'
    child = None
    mounted = []
    try:
        (live / 'active').mkdir(parents=True)
        (live / 'active/sentinel').write_text('initial')
        (destination / 'active').mkdir()
        child = subprocess.Popen([sys.executable, '-c', CHILD, str(live)],
                                 cwd=live / 'active', stdin=subprocess.PIPE,
                                 stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True)
        assert child.stdout.readline().strip() == 'ready'
        legacy.mkdir()
        subprocess.run(['mount', '-o', 'bind,private', str(live), str(legacy)], check=True)
        mounted.append(legacy)
        subprocess.run(['mount', '-o', 'bind,private', str(legacy / 'active'),
                        str(destination / 'active')], check=True)
        mounted.append(destination / 'active')
        subprocess.run(['mount', '-o', 'rbind,rprivate', str(destination), str(live)], check=True)
        mounted.append(live)
        output, error = child.communicate('verify\n', timeout=30)
        if child.returncode != 0:
            raise RuntimeError(error)
        result = json.loads(output)
        assert result['same_process'] == child.pid
        return result
    finally:
        if child is not None and child.poll() is None:
            child.terminate()
            child.wait(timeout=10)
        for path in reversed(mounted):
            # Path.is_mount misses bind mounts on the same filesystem.
            found = subprocess.run(['findmnt', '--mountpoint', str(path), '-n'],
                                   capture_output=True, text=True)
            if found.returncode == 0:
                subprocess.run(['umount', '-R', str(path)], check=True)
        # Both trees were generated by mkdtemp and contain only this fixture.
        shutil.rmtree(source)
        shutil.rmtree(destination)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--volume', required=True)
    args = parser.parse_args()
    print(json.dumps(run(args.volume), sort_keys=True))
