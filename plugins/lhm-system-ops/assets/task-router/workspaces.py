"""Root-owned persistent client workspaces and a generated Obsidian location index."""
import json
import os
from pathlib import Path
import re
import subprocess

ROOT = Path('/var/lib/lhm-client-workspaces')
REGISTRY = Path('/var/lib/lhm-task-router/client-workspaces.md')
REMOTE = 'lhm-knowledge:30 Projects/TED Client Workspaces.md'
LEGACY = {'wellness-chiropractic': Path('/home/codexworker/clients/wellness-chiropractic'),
          'raise-the-bar': Path('/home/codexworker/clients/raise-the-bar')}
MARKER = '<!-- Generated by TED workspace registry; locations only, no task content. -->'


def location(provider, client_id):
    if provider not in {'codex', 'claude'} or not re.fullmatch(r'[a-z0-9][a-z0-9-]{0,79}', client_id):
        raise ValueError('Invalid client workspace identity')
    return LEGACY[client_id] if provider == 'codex' and client_id in LEGACY else ROOT / provider / client_id


def safe_directory(path, uid=0, mode=0o755):
    if path.is_symlink():
        raise ValueError('Workspace directories must not be symlinks')
    path.mkdir(exist_ok=True, mode=mode)
    if not path.is_dir() or path.stat().st_uid != uid:
        raise ValueError('Unexpected workspace ownership')
    path.chmod(mode)


def provision(request, uid):
    provider, client_id = request['provider'], request['client_id']
    root = location(provider, client_id)
    if not re.fullmatch(r'ted-route-[1-9][0-9]*-dm[1-9][0-9]*', request['request_id']):
        raise ValueError('Invalid workspace request ID')
    for path in [ROOT, ROOT / provider]:
        safe_directory(path)
    if root in LEGACY.values():
        if root.is_symlink() or not root.is_dir() or root.stat().st_uid not in {0, uid}:
            raise ValueError('Existing pilot workspace is unavailable or untrusted')
    else:
        safe_directory(root)
    for path in [root / 'tasks', root / '.control']:
        safe_directory(path)
    for name in ['.git', '.codex', '.agents']:
        anchor = root / name
        if not anchor.exists():
            safe_directory(anchor, mode=0o555)
        elif anchor.is_symlink():
            raise ValueError('Workspace anchors cannot be symlinks')
    metadata = {'client_id': client_id, 'provider': provider, 'host': 'hermes-vps',
                'workspace': str(root), 'canonical_overview': request['client'].get('canonical_overview', ''),
                'name': request['client']['name']}
    target = root / '.workspace.json'
    if target.exists():
        if target.is_symlink() or target.stat().st_uid != 0:
            raise ValueError('Untrusted workspace registration')
        saved = json.loads(target.read_text())
        if any(saved.get(k) != metadata[k] for k in ['client_id', 'provider', 'workspace']):
            raise ValueError('Workspace identity collision')
    else:
        target.write_text(json.dumps(metadata, indent=2) + '\n')
        target.chmod(0o644)
    lock = root / '.control/worker.lock'
    if not lock.exists():
        lock.touch(mode=0o444)
    if lock.is_symlink() or lock.stat().st_uid != 0:
        raise ValueError('Untrusted workspace lock')
    (root / '.control').chmod(0o555)
    task = root / 'tasks' / request['request_id']
    task.mkdir(mode=0o750)  # Never overwrite an admitted intake or a previous draft.
    os.chown(task, uid, uid)
    return root, task


def registry_text():
    lines = ['# TED Client Workspaces', '', MARKER, '',
             'Persistent working copies on `hermes-vps`. Knowledge stays in the canonical client notes; Drive files and Git repositories remain their own delivery destinations.', '',
             'New tasks reuse the client/provider workspace. Each request has its own `tasks/<request-id>/` context and drafts; chats remain separate and feedback resumes the original chat.', '']
    for provider in ['codex', 'claude']:
        folders = list((ROOT / provider).glob('*')) + (list(LEGACY.values()) if provider == 'codex' else [])
        for folder in sorted(folders):
            if folder.is_symlink() or not folder.is_dir():
                continue
            metadata = folder / '.workspace.json'
            if metadata.is_symlink() or not metadata.is_file() or metadata.stat().st_uid != 0:
                continue
            entry = json.loads(metadata.read_text())
            if location(provider, entry['client_id']) != folder:
                raise ValueError('Invalid persisted workspace identity')
            name = re.sub(r'[\r\n|<>]', ' ', entry['name'])[:120]
            note = entry.get('canonical_overview', '')
            lines += [f'## {name} — {provider}', f'- Host: `hermes-vps`', f'- Workspace: `{folder}`']
            if note.startswith('20 Clients/') and '..' not in Path(note).parts and note.endswith('.md'):
                lines.append('- Client knowledge: [[' + note[:-3] + ']]')
            lines.append('')
    return '\n'.join(lines) + '\n'


def publish_registry():
    body = registry_text()
    # Fixed generated destination only. Never rewrite a client overview or mutate the old bisync mirror.
    prior = subprocess.run(['/usr/local/bin/rclone', 'cat', REMOTE, '--config', '/etc/lhm-obsidian-sync/rclone.conf'],
                           capture_output=True, text=True, timeout=30)
    if prior.returncode == 0:
        if MARKER not in prior.stdout:
            raise ValueError('Existing Obsidian registry is not our generated note')
        if prior.stdout == body:
            return
    elif prior.returncode not in {3, 4}:
        raise ValueError('Cannot verify Obsidian workspace registry destination')
    REGISTRY.write_text(body)
    REGISTRY.chmod(0o644)
    subprocess.run(['/usr/local/bin/rclone', 'copyto', str(REGISTRY), REMOTE,
                    '--config', '/etc/lhm-obsidian-sync/rclone.conf', '--log-level', 'ERROR'], check=True, timeout=45)
    check = subprocess.run(['/usr/local/bin/rclone', 'cat', REMOTE, '--config', '/etc/lhm-obsidian-sync/rclone.conf'],
                           capture_output=True, text=True, timeout=30, check=True)
    if check.stdout != body:
        raise ValueError('Obsidian workspace registry readback mismatch')
